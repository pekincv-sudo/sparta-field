"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const Money = require("../money.js");
const Cash = require("../cash-ledger.js");
const Warehouse = require("../warehouse-core.js");
module.exports = function () {
  let passed = 0;
  assert.equal(Money.defaultCurrency, "USD");
  assert.equal(Money.normalize(undefined), "UAH");
  assert.throws(() => Money.normalize("EUR"));
  assert.match(Money.format(1234.56), /1\s234,56 USD/);
  assert.match(Money.format(1234.56, "UAH"), /1\s234,56 грн/);
  assert.equal(Money.format(NaN), "—"); passed++;
  const input = { id:"usd",companyId:"company",direction:"income",category:"other_income",amount:"100.29",counterparty:"Owner",purpose:"Opening",occurredAt:"2026-10-25T12:00:00Z",createdAt:"2026-10-25T12:00:00Z",createdBy:"owner",method:"cash" };
  const usd = Cash.createEntry(input);
  assert.equal(usd.currency,"USD"); assert.equal(usd.amountMinor,10029);
  const old = Cash.validateEntry({...usd,id:"old",currency:undefined});
  assert.equal(old.currency,"UAH"); assert.equal(old.amountMinor,usd.amountMinor); passed++;
  assert.throws(() => Cash.totals([usd,old]),/окремо/);
  assert.equal(Cash.totals([usd,old],"USD").balanceMinor,10029);
  assert.equal(Cash.totals([usd,old],"UAH").balanceMinor,10029);
  assert.equal(Cash.filterEntries([usd,old],{currency:"USD"}).length,1); passed++;
  const reversal = Cash.reversal([old],old,{id:"reverse",now:input.createdAt,createdBy:"owner",purpose:"Correction"});
  assert.equal(reversal.currency,"UAH");
  assert.equal(Cash.totals([old,reversal],"UAH").balanceMinor,0);
  assert.throws(() => Cash.validateLedger([old,{...reversal,currency:"USD"}]),/Сторнування/); passed++;
  assert.throws(() => Cash.projectTotals([{...old,sourceType:"project",projectId:"p",projectTitle:"Station"}],"p","USD"),/Валюта/);
  assert.match(Cash.exportCsv([usd,old]),/"Валюта"/);
  assert.match(Cash.exportCsv([usd,old]),/"USD"/);
  assert.match(Cash.exportCsv([usd,old]),/"UAH"/); passed++;
  const fresh = Warehouse.validateCatalog([],{id:"panel",name:"Panel",unit:"шт",retailPrice:150.75});
  assert.equal(fresh.currency,"USD");
  assert.throws(() => Warehouse.validateCatalog([{...fresh,currency:undefined,qty:0}],{...fresh,currency:"USD"}),/Валюту/); passed++;
  const state={items:[fresh],documents:[],movements:[],reservations:[]};
  const doc={id:"receipt",currency:"USD",date:"2026-10-25",lines:[{itemId:"panel",qty:2,purchasePrice:100.25,deliveryCost:0.50}]};
  const receipt=Warehouse.postReceipt(state,doc);
  assert.equal(receipt.document.currency,"USD");
  assert.equal(receipt.document.lines[0].currency,"USD");
  assert.equal(receipt.movements[0].currency,"USD");
  assert.equal(receipt.document.total,201.5);
  assert.equal(receipt.items[0].purchasePrice,100.25);
  assert.throws(() => Warehouse.postReceipt(state,{...doc,currency:"UAH"}),/валюті/); passed++;
  const legacy=Warehouse.postReceipt({...state,items:[{...fresh,currency:undefined}]},{...doc,currency:"UAH"});
  assert.equal(legacy.document.currency,"UAH"); assert.equal(legacy.document.total,201.5); passed++;
  const source=fs.readFileSync(require("node:path").join(__dirname,"../app.js"),"utf8");
  const extract=(name)=>{const match=source.match(new RegExp(`function ${name}\\([^]*?\\n\\}`));assert(match);return match[0];};
  const context={window:{SpartaMoney:Money},cloudState:{companyId:"company",user:{id:"owner"},supportsProjectFinance:true},normalizeProjectId:String,emptyProjectFinance:()=>({}),emptyInstallerChecklist:()=>({}),projectFilesFor:()=>[]};
  vm.createContext(context);
  vm.runInContext(["projectToDb","dbProjectToApp","money"].map(extract).join("\n"),context);
  const db= context.projectToDb({id:"p",currency:"USD",finance:{contractPrice:4000.55}});
  assert.equal(db.currency,"USD"); assert.equal(db.finance.contractPrice,4000.55);
  assert.equal(context.dbProjectToApp({...db,client_id:"p"}).currency,"USD");
  assert.equal(context.dbProjectToApp({id:"legacy",finance:{contractPrice:4000.55}}).currency,"UAH"); passed++;
  context.projectMaterialsWithWarehousePrices=()=>[{currency:"UAH",qty:2,purchasePrice:100,salePrice:150}];
  context.normalizeProjectFinance=(finance)=>({expenses:[],...finance});
  vm.runInContext(extract("projectFinanceTotals"),context);
  const mixed=context.projectFinanceTotals({id:"p",currency:"USD",finance:{contractPrice:1000}});
  assert(mixed.currencyMismatch); assert(Number.isNaN(mixed.profit));assert.equal(context.money(mixed.profit,"USD"),"—"); passed++;
  return {passed};
};
